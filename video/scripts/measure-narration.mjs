#!/usr/bin/env node
// Measure narration audio and make it the timing authority.
//
// Two sources are measured:
//   1. The pilot:        <id>.(mp3|wav) in ../narration
//   2. Each module:      <beat-id>.(mp3|wav) in modules/<name>/narration/
//
// Real durations are measured with ffprobe and written out as:
//   ../narration/durations.json            (pilot, seconds per beat)
//   ../src/generated/narration.ts          (pilot audio + durations)
//   modules/<name>/durations.json          (module, seconds per beat)
//   ../src/generated/module-narration.ts   (all module audio + durations)
//
// When no audio files are present the artifacts are written empty and the
// compositions fall back to estSeconds. Run it again after dropping in new
// narration files (the supervisor does this before the final render).
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const videoRoot = dirname(dirname(fileURLToPath(import.meta.url)));

function measureDir(dir, allowedBeatIds) {
  const durations = {};
  const files = {};
  if (!existsSync(dir)) return { durations, files };
  const entries = readdirSync(dir).filter((f) => /\.(mp3|wav|m4a)$/i.test(f));
  for (const file of entries) {
    const id = file.replace(/\.(mp3|wav|m4a)$/i, '');
    if (allowedBeatIds && !allowedBeatIds.has(id)) {
      console.log(`  skip ${file} (not a beat id)`);
      continue;
    }
    const path = join(dir, file);
    const probe = execFileSync(
      'ffprobe',
      ['-v', 'error', '-show_entries', 'format=duration', '-of', 'json', path],
      { encoding: 'utf8' }
    );
    const sec = Number(JSON.parse(probe).format.duration);
    durations[id] = sec;
    files[id] = file;
  }
  return { durations, files };
}

// ---- Pilot -----------------------------------------------------------------
const narrationDir = join(videoRoot, 'narration');
const outJson = join(narrationDir, 'durations.json');
const outTs = join(videoRoot, 'src', 'generated', 'narration.ts');

const pilotScript = JSON.parse(readFileSync(join(videoRoot, 'script.json'), 'utf8'));
const pilotIds = new Set(pilotScript.beats.map((b) => b.id));
const pilot = measureDir(narrationDir, pilotIds);

writeFileSync(outJson, JSON.stringify(pilot.durations, null, 2) + '\n');

const lines = [
  `// AUTO-GENERATED by scripts/measure-narration.mjs — do not edit.`,
  `// Duration source: ${Object.keys(pilot.durations).length > 0 ? 'narration audio (real durations)' : 'estSeconds fallback (no audio)'}.`,
  `// Run \`npm run measure\` after adding narration files.`,
  '',
];
for (const id of Object.keys(pilot.files)) {
  const v = id.replace(/[^A-Za-z0-9_]/g, '_');
  lines.push(`import ${v} from '../../narration/${pilot.files[id]}';`);
}
lines.push('');
lines.push('export const audioSources: Record<string, string> = {');
for (const id of Object.keys(pilot.files)) {
  const v = id.replace(/[^A-Za-z0-9_]/g, '_');
  lines.push(`  ${JSON.stringify(id)}: ${v},`);
}
lines.push('};');
lines.push('');
lines.push('export const durations: Record<string, number> = {');
for (const id of Object.keys(pilot.durations)) {
  lines.push(`  ${JSON.stringify(id)}: ${pilot.durations[id]},`);
}
lines.push('};');
writeFileSync(outTs, lines.join('\n') + '\n');

console.log(
  `Pilot: measured ${Object.keys(pilot.files).length} narration file(s). ` +
    `Wrote narration/durations.json and generated/narration.ts.`
);

// ---- Modules ---------------------------------------------------------------
const modulesDir = join(videoRoot, 'modules');
const moduleAudio = {}; // moduleName -> beatId -> audio file
const moduleDur = {};   // moduleName -> beatId -> seconds

if (existsSync(modulesDir)) {
  for (const name of readdirSync(modulesDir, { withFileTypes: true })) {
    if (!name.isDirectory()) continue;
    const scriptPath = join(modulesDir, name.name, 'script.json');
    if (!existsSync(scriptPath)) {
      console.log(`  skip ${name.name} (no script.json)`);
      continue;
    }
    const ids = new Set(
      JSON.parse(readFileSync(scriptPath, 'utf8')).beats.map((b) => b.id)
    );
    const { durations, files } = measureDir(
      join(modulesDir, name.name, 'narration'),
      ids
    );
    moduleDur[name.name] = durations;
    moduleAudio[name.name] = files;

    // Per-module human-readable durations.json (mirrors the pilot).
    const modJson = join(modulesDir, name.name, 'durations.json');
    writeFileSync(modJson, JSON.stringify(durations, null, 2) + '\n');
    const nTag = Object.keys(files).length ? 'audio' : 'estSeconds fallback';
    console.log(`  ${name.name}: ${Object.keys(files).length} file(s) (${nTag})`);
  }
}

const totalMod = Object.values(moduleDur).reduce((n, d) => n + Object.keys(d).length, 0);
const modLines = [
  `// AUTO-GENERATED by scripts/measure-narration.mjs — do not edit.`,
  `// Duration source: ${totalMod > 0 ? 'module narration audio (real durations)' : 'estSeconds fallback (no audio)'}.`,
  `// Run \`npm run measure\` after adding module narration files.`,
  '',
];
const usedImports = new Set();
for (const name of Object.keys(moduleAudio)) {
  for (const id of Object.keys(moduleAudio[name])) {
    const v = id.replace(/[^A-Za-z0-9_]/g, '_') + '_' + name.replace(/[^A-Za-z0-9_]/g, '_');
    if (usedImports.has(v)) continue;
    usedImports.add(v);
    modLines.push(`import ${v} from '../../modules/${name}/narration/${moduleAudio[name][id]}';`);
  }
}
modLines.push('');
modLines.push('export const moduleAudioSources: Record<string, Record<string, string>> = {');
for (const name of Object.keys(moduleAudio)) {
  modLines.push(`  ${JSON.stringify(name)}: {`);
  for (const id of Object.keys(moduleAudio[name])) {
    const v = id.replace(/[^A-Za-z0-9_]/g, '_') + '_' + name.replace(/[^A-Za-z0-9_]/g, '_');
    modLines.push(`    ${JSON.stringify(id)}: ${v},`);
  }
  modLines.push(`  },`);
}
modLines.push('};');
modLines.push('');
modLines.push('export const moduleDurations: Record<string, Record<string, number>> = {');
for (const name of Object.keys(moduleDur)) {
  modLines.push(`  ${JSON.stringify(name)}: {`);
  for (const id of Object.keys(moduleDur[name])) {
    modLines.push(`    ${JSON.stringify(id)}: ${moduleDur[name][id]},`);
  }
  modLines.push(`  },`);
}
modLines.push('};');
const modOut = join(videoRoot, 'src', 'generated', 'module-narration.ts');
writeFileSync(modOut, modLines.join('\n') + '\n');
console.log(`Modules: wrote generated/module-narration.ts.`);
